// Persian word lexicon for deterministic PDF-text repair (persian-repair.ts).
//
// WHY: Persian PDFs frequently carry text layers whose ligature glyphs are
// decomposed into two characters in REVERSED (visual) order:
//   لا → ال   (اطلاعات → اطالعات، سلامت → سالمت)
//   تر → رت   (کنترل → کنرتل، مشتری → مشرتی، دسترسی → دسرتسی)
//   تن → نت   (متن → منت، داشتن → داشنت، گرفتن → گرفنت)
//   بر → رب   (معتبر → معترب)
// The repair is word-level and lexicon-guarded: a token is ONLY rewritten when
// the token itself is unknown AND a ligature-pair swap yields a known word.
// Entries below are therefore both "repair targets" and "protection" (a known
// token is never touched — e.g. سال/الف/الگو/منتظر contain legit ال/نت).
//
// Keys are ZWNJ-insensitive: "می‌کند" and "میکند" map to the same key.
// Rank (lower = more frequent) is only a tie-break between candidates.

function buildLexicon(groups: Array<[rank: number, words: string[]]>): Map<string, number> {
  const map = new Map<string, number>();
  for (const [rank, words] of groups) {
    for (const w of words) {
      const key = w.replace(/\u200C/g, '');
      if (key.length > 0 && !map.has(key)) map.set(key, rank);
    }
  }
  return map;
}

